SELECT Visits.customer_id,
       COUNT(*) AS count_no_trans /* YE COUNT KA DIRECT METHOD HOTA H  ME ISME COUNT KO AS COUNT_NO_TRANS MAAN RAHA HU OK */
FROM Visits
LEFT JOIN Transactions/* HERE  I AM DOING LEFT JOIN USE BECAUSE I AM FINDING TRANSACTION IN WHICH TRANSACTION IS NULL THATSWHY HERE WE ARE USING LEFT JOIN ? WHY NOT USING INNER JOIN BECAUSE INNER JOIN JUST JOINS THE VALUES TOGETHER ONLY */
ON Visits.visit_id = Transactions.visit_id /* HERE I AM TRYING TO CHECK */
WHERE Transactions.transaction_id IS NULL/*HERE I AM FINDING NULL VALUE DIRECTLY AND THEN GROUPING THAT VALUE */
GROUP BY Visits.customer_id;
